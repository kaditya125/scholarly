export function classifySocialWorkQuestion(text: string): { unitNumber: number; unitCode: string; unitName: string } {
  const lower = text.toLowerCase();

  // Unit 3: Case Work & Group Work
  if (lower.includes('case work') || lower.includes('casework') || lower.includes('group work') || lower.includes('groupwork') ||
      lower.includes('perlman') || lower.includes('individualization') || lower.includes('sociometry') || lower.includes('psychosocial') ||
      lower.includes('treatment') || lower.includes('diagnosis') || lower.includes('client-centered')) {
    return { unitNumber: 3, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[2].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[2].unitName };
  }

  // Unit 4: Community Organization & Social Action
  if (lower.includes('community organization') || lower.includes('social action') || lower.includes('rothman') ||
      lower.includes('paulo freire') || lower.includes('conscientization') || lower.includes('alinsky') ||
      lower.includes('advocacy') || lower.includes('social movement') || lower.includes('pra') || lower.includes('participatory rural')) {
    return { unitNumber: 4, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[3].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[3].unitName };
  }

  // Unit 5: Social Work Research
  if (lower.includes('research') || lower.includes('hypothesis') || lower.includes('sampling') || lower.includes('chi-square') ||
      lower.includes('t-test') || lower.includes('anova') || lower.includes('correlation') || lower.includes('questionnaire') ||
      lower.includes('variables') || lower.includes('data collection') || lower.includes('methodology')) {
    return { unitNumber: 5, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[4].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[4].unitName };
  }

  // Unit 8: Family, Child, Women, Elderly, PwD
  if (lower.includes('child') || lower.includes('juvenile') || lower.includes('pocso') || lower.includes('women') ||
      lower.includes('domestic violence') || lower.includes('elderly') || lower.includes('senior citizen') ||
      lower.includes('disability') || lower.includes('rpwd') || lower.includes('family') || lower.includes('youth')) {
    return { unitNumber: 8, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[7].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[7].unitName };
  }

  // Unit 9: Health & Mental Health
  if (lower.includes('health') || lower.includes('medical social work') || lower.includes('psychiatric') ||
      lower.includes('mental health') || lower.includes('hospital') || lower.includes('disease') ||
      lower.includes('ayushman') || lower.includes('nutrition') || lower.includes('substance abuse')) {
    return { unitNumber: 9, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[8].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[8].unitName };
  }

  // Unit 6: Administration, Welfare, NGOs
  if (lower.includes('administration') || lower.includes('posdcorb') || lower.includes('ngo') || lower.includes('societies registration') ||
      lower.includes('budgeting') || lower.includes('fund raising') || lower.includes('fcra') || lower.includes('trust act')) {
    return { unitNumber: 6, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[5].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[5].unitName };
  }

  // Unit 7: Social Policy, Development, Legislation
  if (lower.includes('social policy') || lower.includes('social development') || lower.includes('poverty') ||
      lower.includes('mgnrega') || lower.includes('legislation') || lower.includes('pil') || lower.includes('atrocities') ||
      lower.includes('scheduled caste') || lower.includes('tribal') || lower.includes('prison') || lower.includes('probation')) {
    return { unitNumber: 7, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[6].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[6].unitName };
  }

  // Unit 10: Contemporary, CSR, Environment
  if (lower.includes('csr') || lower.includes('corporate social responsibility') || lower.includes('environment') ||
      lower.includes('disaster') || lower.includes('labor') || lower.includes('labour') || lower.includes('factories act') ||
      lower.includes('industrial dispute') || lower.includes('trafficking') || lower.includes('migration')) {
    return { unitNumber: 10, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[9].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[9].unitName };
  }

  // Unit 2: Society, Human Behavior
  if (lower.includes('society') || lower.includes('sociology') || lower.includes('culture') || lower.includes('socialization') ||
      lower.includes('caste') || lower.includes('freud') || lower.includes('erikson') || lower.includes('piaget') ||
      lower.includes('personality') || lower.includes('learning theory') || lower.includes('attitude') || lower.includes('group dynamics')) {
    return { unitNumber: 2, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[1].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[1].unitName };
  }

  // Default to Unit 1: Nature and Development of Social Work
  return { unitNumber: 1, unitCode: UGC_NET_SOCIAL_WORK_TAXONOMY[0].unitCode, unitName: UGC_NET_SOCIAL_WORK_TAXONOMY[0].unitName };
}
