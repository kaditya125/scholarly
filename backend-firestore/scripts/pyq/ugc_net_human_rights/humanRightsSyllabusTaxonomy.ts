export function mapQuestionToHumanRightsUnit(questionText: string): { unitNumber: number; unitName: string } {
  const text = questionText.toLowerCase();

  // Unit 10: International Enforcement (Courts, Treaty bodies, UPR)
  if (
    text.includes('european court of human rights') || text.includes('echr') ||
    text.includes('inter-american court') || text.includes('african court') ||
    text.includes('universal periodic review') || text.includes('upr') ||
    text.includes('treaty body') || text.includes('treaty bodies') ||
    text.includes('human rights committee') || text.includes('cescr') ||
    text.includes('cedaw committee') || text.includes('special procedures')
  ) {
    return { unitNumber: 10, unitName: 'International Enforcement of Human Rights' };
  }

  // Unit 9: Constitutional Governance (NHRC, Criminal Justice, AFSPA, Emergency)
  if (
    text.includes('nhrc') || text.includes('shrc') || text.includes('protection of human rights act') ||
    text.includes('preventive detention') || text.includes('afspa') || text.includes('armed forces special') ||
    text.includes('criminal justice') || text.includes('cr.p.c') || text.includes('crpc') || text.includes('ipc') ||
    text.includes('custodial') || text.includes('police reforms') || text.includes('emergency') ||
    text.includes('good governance') || text.includes('rule of law')
  ) {
    return { unitNumber: 9, unitName: 'Constitutional Governance' };
  }

  // Unit 8: Indian Constitution & Human Rights (Fundamental Rights, DPSP, PIL)
  if (
    text.includes('fundamental rights') || text.includes('directive principles') || text.includes('dpsp') ||
    text.includes('article 21') || text.includes('article 14') || text.includes('article 19') ||
    text.includes('article 32') || text.includes('article 226') || text.includes('public interest litigation') ||
    text.includes('pil') || text.includes('fundamental duties') || text.includes('maneka gandhi') ||
    text.includes('kesavananda') || text.includes('indian constitution')
  ) {
    return { unitNumber: 8, unitName: 'Human Rights and Indian Constitution' };
  }

  // Unit 7: Development, Underdevelopment & Social Action (Commissions, Movements)
  if (
    text.includes('national commission for women') || text.includes('ncw') || text.includes('ncpcr') ||
    text.includes('chipko') || text.includes('narmada bachao') || text.includes('dalit movement') ||
    text.includes('peasant movement') || text.includes('agrarian') || text.includes('social movement') ||
    text.includes('environmental movement') || text.includes('social action')
  ) {
    return { unitNumber: 7, unitName: 'Development, Underdevelopment and Social Action' };
  }

  // Unit 6: Growth Models & Human Rights (Development, WTO, TRIPS, Sustainable Development)
  if (
    text.includes('wto') || text.includes('trips') || text.includes('trims') || text.includes('gats') ||
    text.includes('transnational corporation') || text.includes('tnc') || text.includes('sustainable development') ||
    text.includes('agenda 21') || text.includes('rio declaration') || text.includes('right to development') ||
    text.includes('minimum wages') || text.includes('right to food')
  ) {
    return { unitNumber: 6, unitName: 'Growth Models and Human Rights' };
  }

  // Unit 5: UN & Various Agencies, IGOs & INGOs (UN Organs, Amnesty, HRW, PUCL)
  if (
    text.includes('united nations') || text.includes('un charter') || text.includes('general assembly') ||
    text.includes('security council') || text.includes('ecosoc') || text.includes('human rights council') ||
    text.includes('unhrc') || text.includes('amnesty international') || text.includes('human rights watch') ||
    text.includes('unicef') || text.includes('unesco') || text.includes('ilo') || text.includes('who') ||
    text.includes('unhcr') || text.includes('pucl') || text.includes('pudr')
  ) {
    return { unitNumber: 5, unitName: 'UN and Various Agencies, IGOs and INGOs' };
  }

  // Unit 4: State and Individual Liberty (IHL, Geneva Conventions, ICC, Red Cross)
  if (
    text.includes('humanitarian law') || text.includes('geneva convention') || text.includes('red cross') ||
    text.includes('international criminal court') || text.includes('icc') || text.includes('ictr') ||
    text.includes('icty') || text.includes('welfare state') || text.includes('repressive state') ||
    text.includes('self-determination') || text.includes('sovereignty')
  ) {
    return { unitNumber: 4, unitName: 'State and Individual Liberty' };
  }

  // Unit 3: Society, Economy, Polity, Religion & Culture (Discrimination, Child, Women, Refugees, PwD)
  if (
    text.includes('caste') || text.includes('child labour') || text.includes('child abuse') ||
    text.includes('domestic violence') || text.includes('bonded labour') || text.includes('refugee') ||
    text.includes('disability') || text.includes('pwds') || text.includes('trafficking') ||
    text.includes('gender discrimination') || text.includes('slums') || text.includes('social stratification')
  ) {
    return { unitNumber: 3, unitName: 'Society, Economy, Polity, Religion and Culture: Their Inter-Relationship' };
  }

  // Unit 2: Origin & Evolution (UDHR, Magna Carta, ICCPR, ICESCR, CEDAW)
  if (
    text.includes('udhr') || text.includes('universal declaration') || text.includes('magna carta') ||
    text.includes('iccpr') || text.includes('icescr') || text.includes('cedaw') ||
    text.includes('natural rights') || text.includes('french revolution') || text.includes('american declaration') ||
    text.includes('vienna declaration') || text.includes('helsinki') || text.includes('responsibility to protect')
  ) {
    return { unitNumber: 2, unitName: 'Origin and Evolution of Human Rights and International Standards' };
  }

  // Unit 1: Concept and Nature (Default)
  return { unitNumber: 1, unitName: 'Human Rights and Duties: Concept and Nature' };
}
