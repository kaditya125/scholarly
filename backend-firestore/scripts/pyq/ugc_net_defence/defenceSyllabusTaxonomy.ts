export function mapDefenceTopicToUnit(text: string): { unitNumber: number; unitName: string } {
  const lower = text.toLowerCase();

  // Unit 8: Disaster Management
  if (
    lower.includes('disaster') || lower.includes('tsunami') || lower.includes('earthquake') ||
    lower.includes('cyclone') || lower.includes('flood') || lower.includes('ndma') ||
    lower.includes('ndrf') || lower.includes('sendai framework') || lower.includes('hyogo') ||
    lower.includes('bhopal gas') || lower.includes('chernobyl') || lower.includes('fukushima') ||
    lower.includes('incois') || lower.includes('mitigation') || lower.includes('hazard') ||
    lower.includes('vulnerability')
  ) {
    return { unitNumber: 8, unitName: 'Disaster Management and National Security' };
  }

  // Unit 4: WMD, Nuclear Proliferation & Arms Control
  if (
    lower.includes('npt') || lower.includes('ctbt') || lower.includes('wmd') ||
    lower.includes('chemical weapon') || lower.includes('biological weapon') ||
    lower.includes('cwc') || lower.includes('bwc') || lower.includes('arms control') ||
    lower.includes('disarmament') || lower.includes('ptbt') || lower.includes('mtcr') ||
    lower.includes('nsg') || lower.includes('wassenaar') || lower.includes('australia group') ||
    lower.includes('salt i') || lower.includes('salt ii') || lower.includes('start treaty') ||
    lower.includes('star wars') || lower.includes('missile defense') || lower.includes('fmct') ||
    lower.includes('opcw') || lower.includes('iaea')
  ) {
    return { unitNumber: 4, unitName: 'WMD, Nuclear Proliferation and National Security' };
  }

  // Unit 9: Defence Economics
  if (
    lower.includes('defence expenditure') || lower.includes('defence budget') ||
    lower.includes('economic cause') || lower.includes('gun vs butter') ||
    lower.includes('economic warfare') || lower.includes('defence economics') ||
    lower.includes('procurement procedure') || lower.includes('dap') || lower.includes('dpp') ||
    lower.includes('defence planning') || lower.includes('geo-economics') || lower.includes('trade sanction') ||
    lower.includes('wto') || lower.includes('trips') || lower.includes('trims') ||
    lower.includes('brics') || lower.includes('g20') || lower.includes('military expenditure')
  ) {
    return { unitNumber: 9, unitName: 'Defence Economics' };
  }

  // Unit 10: Science & Technology and National Security
  if (
    lower.includes('drdo') || lower.includes('igmdp') || lower.includes('brahmos') ||
    lower.includes('revolution in military affairs') || lower.includes('rma') ||
    lower.includes('cyber') || lower.includes('c4isr') || lower.includes('precision guided') ||
    lower.includes('military industrial complex') || lower.includes('dpsu') ||
    lower.includes('ordnance factory') || lower.includes('isro') || lower.includes('navic') ||
    lower.includes('electronic warfare') || lower.includes('artificial intelligence') ||
    lower.includes('drone') || lower.includes('uav') || lower.includes('dual use technology') ||
    lower.includes('science and technology') || lower.includes('social media') || lower.includes('information warfare')
  ) {
    return { unitNumber: 10, unitName: 'Science & Technology and National Security' };
  }

  // Unit 7: Conflict Resolution
  if (
    lower.includes('conflict resolution') || lower.includes('conflict management') ||
    lower.includes('peacekeeping') || lower.includes('peace keeping') || lower.includes('peacemaking') ||
    lower.includes('peacebuilding') || lower.includes('confidence building') || lower.includes('cbm') ||
    lower.includes('geneva convention') || lower.includes('laws of armed conflict') || lower.includes('loac') ||
    lower.includes('international humanitarian law') || lower.includes('ihl') ||
    lower.includes('pacific settlement') || lower.includes('chapter vi') || lower.includes('chapter vii') ||
    lower.includes('un security council') || lower.includes('gandhian philosophy') || lower.includes('satyagraha') ||
    lower.includes('mediation') || lower.includes('arbitration')
  ) {
    return { unitNumber: 7, unitName: 'Issues in Conflict Resolution' };
  }

  // Unit 2: Strategic Thought
  if (
    lower.includes('sun tzu') || lower.includes('kautilya') || lower.includes('machiavelli') ||
    lower.includes('clausewitz') || lower.includes('jomini') || lower.includes('douhet') ||
    lower.includes('billy mitchell') || lower.includes('liddell hart') || lower.includes('fuller') ||
    lower.includes('mao zedong') || lower.includes('che guevara') || lower.includes('andre beaufre') ||
    lower.includes('henry kissinger') || lower.includes('k. subrahmanyam') || lower.includes('subrahmanyam') ||
    lower.includes('arthashastra') || lower.includes('mandala') || lower.includes('saptanga') ||
    lower.includes('principles of war') || lower.includes('indirect approach') || lower.includes('strategic thought')
  ) {
    return { unitNumber: 2, unitName: 'Strategic Thought' };
  }

  // Unit 6: India\'s Security Concerns & Policies
  if (
    lower.includes('india') || lower.includes('sino-indian') || lower.includes('indo-pak') ||
    lower.includes('pakistan') || lower.includes('china') || lower.includes('kashmir') ||
    lower.includes('siachen') || lower.includes('sir creek') || lower.includes('lac') ||
    lower.includes('line of actual control') || lower.includes('loc') || lower.includes('kargil') ||
    lower.includes('look east') || lower.includes('act east') || lower.includes('indo-pacific') ||
    lower.includes('quad') || lower.includes('indian ocean') || lower.includes('cpec') ||
    lower.includes('obor') || lower.includes('doklam') || lower.includes('galwan') ||
    lower.includes('chief of defence staff') || lower.includes('cds') || lower.includes('higher defence') ||
    lower.includes('theatre command') || lower.includes('nuclear doctrine of india') || lower.includes('no first use')
  ) {
    return { unitNumber: 6, unitName: 'India\'s Security Concerns & Policies in Contemporary International Scenario' };
  }

  // Unit 3: War as an Instrument in International Relations
  if (
    lower.includes('causes of war') || lower.includes('limited war') || lower.includes('guerrilla warfare') ||
    lower.includes('insurgency') || lower.includes('counter-insurgency') || lower.includes('coin') ||
    lower.includes('low intensity') || lower.includes('terrorism') || lower.includes('cross border terrorism') ||
    lower.includes('deterrence') || lower.includes('mutually assured destruction') || lower.includes('mad') ||
    lower.includes('flexible response') || lower.includes('massive retaliation') ||
    lower.includes('democratic peace') || lower.includes('militarism') || lower.includes('irredentism')
  ) {
    return { unitNumber: 3, unitName: 'War as an Instrument in International Relations' };
  }

  // Unit 5: Global Security Concerns
  if (
    lower.includes('global warming') || lower.includes('climate change') || lower.includes('refugee') ||
    lower.includes('migration') || lower.includes('arab spring') || lower.includes('palestinian') ||
    lower.includes('israel') || lower.includes('korean peninsula') || lower.includes('taiwan') ||
    lower.includes('south china sea') || lower.includes('narco') || lower.includes('human trafficking') ||
    lower.includes('money laundering') || lower.includes('unhcr') || lower.includes('red cross') ||
    lower.includes('energy security') || lower.includes('food security') || lower.includes('water security') ||
    lower.includes('millennium development') || lower.includes('sdg')
  ) {
    return { unitNumber: 5, unitName: 'Global Security Concerns' };
  }

  // Unit 1: Theories and Concepts (Default)
  return { unitNumber: 1, unitName: 'Theories and Concepts' };
}
