export function mapQuestionToTourismUnit(questionText: string): { unitNumber: number; unitName: string } {
  const text = questionText.toLowerCase();

  // Unit 10: Management & Accounting
  if (
    text.includes('balance sheet') || text.includes('profit and loss') || text.includes('double entry') ||
    text.includes('break-even') || text.includes('break even') || text.includes('working capital') ||
    text.includes('budgetary control') || text.includes('maslow') || text.includes('herzberg') ||
    text.includes('fayol') || text.includes('organizational behaviour') || text.includes('leadership style') ||
    text.includes('managerial') || text.includes('cost-volume-profit')
  ) {
    return { unitNumber: 10, unitName: 'Management Functions, Organizational Behaviour and Financial Accounting' };
  }

  // Unit 9: Research Methodology & Statistics
  if (
    text.includes('hypothesis') || text.includes('sampling') || text.includes('chi-square') ||
    text.includes('anova') || text.includes('t-test') || text.includes('regression') ||
    text.includes('delphi method') || text.includes('demand forecasting') || text.includes('questionnaire') ||
    text.includes('research design') || text.includes('primary data') || text.includes('secondary data') ||
    text.includes('sample size') || text.includes('correlation')
  ) {
    return { unitNumber: 9, unitName: 'Research Methodology and Statistical Applications in Tourism' };
  }

  // Unit 8: Tourism Planning & Policy & Sustainability
  if (
    text.includes('carrying capacity') || text.includes('environmental impact assessment') ||
    text.includes('eia') || text.includes('sustainable tourism') || text.includes('swadesh darshan') ||
    text.includes('prashad') || text.includes('national tourism policy') || text.includes('multiplier effect') ||
    text.includes('leakage') || text.includes('ecotourism') || text.includes('responsible tourism') ||
    text.includes('community based tourism') || text.includes('tourism planning')
  ) {
    return { unitNumber: 8, unitName: 'Tourism Planning, Policy and Sustainable Development' };
  }

  // Unit 7: Tourism Marketing & Branding
  if (
    text.includes('marketing mix') || text.includes('7 ps') || text.includes('4 ps') ||
    text.includes('destination marketing') || text.includes('market segmentation') ||
    text.includes('positioning') || text.includes('advertising') || text.includes('public relations') ||
    text.includes('incredible india') || text.includes('online travel agency') || text.includes('ota') ||
    text.includes('promotion mix') || text.includes('branding')
  ) {
    return { unitNumber: 7, unitName: 'Tourism Marketing, Destination Branding and PR' };
  }

  // Unit 6: Hospitality Industry & Accommodation
  if (
    text.includes('hotel') || text.includes('hospitality') || text.includes('front office') ||
    text.includes('housekeeping') || text.includes('revpar') || text.includes('night audit') ||
    text.includes('european plan') || text.includes('continental plan') || text.includes('american plan') ||
    text.includes('modified american plan') || text.includes('food and beverage') || text.includes('f&b') ||
    text.includes('star rating') || text.includes('hracc') || text.includes('room service')
  ) {
    return { unitNumber: 6, unitName: 'Hospitality Industry, Accommodation and Catering' };
  }

  // Unit 5: Travel Trade & Tour Operations & Itinerary
  if (
    text.includes('travel agency') || text.includes('tour operator') || text.includes('thomas cook') ||
    text.includes('itinerary') || text.includes('gds') || text.includes('amadeus') ||
    text.includes('sabre') || text.includes('galileo') || text.includes('travel information manual') ||
    text.includes('tim') || text.includes('passport') || text.includes('visa') ||
    text.includes('taai') || text.includes('tour packaging')
  ) {
    return { unitNumber: 5, unitName: 'Travel Trade, Tour Operations and Itinerary Planning' };
  }

  // Unit 4: Transport Systems & Aviation
  if (
    text.includes('airline') || text.includes('air transport') || text.includes('freedoms of the air') ||
    text.includes('chicago convention') || text.includes('icao') || text.includes('railways') ||
    text.includes('palace on wheels') || text.includes('maharaja express') || text.includes('cruise') ||
    text.includes('surface transport') || text.includes('dgca') || text.includes('low cost carrier') ||
    text.includes('aviation') || text.includes('irctc')
  ) {
    return { unitNumber: 4, unitName: 'Transport Systems and Tourism Mobility' };
  }

  // Unit 3: Tourism Products of India
  if (
    text.includes('unesco world heritage') || text.includes('national park') ||
    text.includes('wildlife sanctuary') || text.includes('biosphere reserve') ||
    text.includes('temple') || text.includes('monument') || text.includes('beach resort') ||
    text.includes('hill station') || text.includes('pilgrimage') || text.includes('handicrafts') ||
    text.includes('classical dance') || text.includes('heritage site') || text.includes('tourism product')
  ) {
    return { unitNumber: 3, unitName: 'Tourism Products and Heritage Resources of India' };
  }

  // Unit 2: Tourism Geography
  if (
    text.includes('gmt') || text.includes('latitude') || text.includes('longitude') ||
    text.includes('time zone') || text.includes('international date line') || text.includes('iata area') ||
    text.includes('airport code') || text.includes('city code') || text.includes('tc1') ||
    text.includes('tc2') || text.includes('tc3') || text.includes('world geography') ||
    text.includes('seasonality')
  ) {
    return { unitNumber: 2, unitName: 'Tourism Geography and Travel Patterns' };
  }

  // Unit 1: Concepts & Principles (Default)
  return { unitNumber: 1, unitName: 'Tourism Concepts and Principles' };
}

