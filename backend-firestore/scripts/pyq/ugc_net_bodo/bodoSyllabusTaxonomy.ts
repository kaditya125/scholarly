export function mapQuestionToBodoUnit(questionText: string): { unitNumber: number; unitName: string } {
  const text = questionText.toLowerCase();

  // Unit 10: Society, Bathouism, Brahma Movement, Language Movement, 8th Schedule
  if (
    text.includes('bathou') || text.includes('sijou') || text.includes('brahma dharma') ||
    text.includes('kalicharan') || text.includes('language movement') || text.includes('script movement') ||
    text.includes('eighth schedule') || text.includes('8th schedule') || text.includes('bodo sahitya sabha') ||
    text.includes('absu') || text.includes('clan') || text.includes('marriage') || text.includes('hathasuni') ||
    text.includes('bodoland')
  ) {
    return { unitNumber: 10, unitName: 'Bodo Society, Culture and Language Movement' };
  }

  // Unit 9: Literary Theory, Poetics & Comparative Studies
  if (
    text.includes('rasa') || text.includes('dhvani') || text.includes('alankara') ||
    text.includes('poetics') || text.includes('aristotle') || text.includes('romanticism') ||
    text.includes('structuralism') || text.includes('comparative literature') || text.includes('translation') ||
    text.includes('literary theory') || text.includes('criticism') || text.includes('subaltern')
  ) {
    return { unitNumber: 9, unitName: 'Literary Theory, Poetics and Comparative Literature' };
  }

  // Unit 8: Folklore, Folk Songs, Bwisagu, Kherai
  if (
    text.includes('folklore') || text.includes('folktale') || text.includes('bwisagu') ||
    text.includes('kherai') || text.includes('garja') || text.includes('solobatha') ||
    text.includes('proverb') || text.includes('riddle') || text.includes('folk song') ||
    text.includes('methai') || text.includes('oral tradition') || text.includes('myth')
  ) {
    return { unitNumber: 8, unitName: 'Bodo Folklore, Folk Culture and Oral Traditions' };
  }

  // Unit 7: Prose, Essays, Non-Fiction & Critics
  if (
    text.includes('prose') || text.includes('essay') || text.includes('biography') ||
    text.includes('autobiography') || text.includes('travelogue') || text.includes('non-fiction') ||
    text.includes('critic') || text.includes('kameshwar') || text.includes('phukan chandra') ||
    text.includes('mangalsingh')
  ) {
    return { unitNumber: 7, unitName: 'Bodo Prose and Non-Fictional Literature' };
  }

  // Unit 6: Drama & Theatre
  if (
    text.includes('drama') || text.includes('theatre') || text.includes('play') ||
    text.includes('satish chandra basumatary') || text.includes('kamal kumar brahma') ||
    text.includes('bidyasagar') || text.includes('stage') || text.includes('natok')
  ) {
    return { unitNumber: 6, unitName: 'Bodo Drama and Performing Arts' };
  }

  // Unit 5: Fiction: Novel & Short Story
  if (
    text.includes('novel') || text.includes('short story') || text.includes('fiction') ||
    text.includes('chittaranjan mushahary') || text.includes('manoranjan lahary') ||
    text.includes('dharanidhar wary') || text.includes('nilkamal brahma') || text.includes('character')
  ) {
    return { unitNumber: 5, unitName: 'Bodo Fiction: Novel and Short Story' };
  }

  // Unit 4: Poetry
  if (
    text.includes('poetry') || text.includes('poem') || text.includes('poet') ||
    text.includes('ishan chandra') || text.includes('rupnath brahma') || text.includes('pramod chandra') ||
    text.includes('bhaben narzary') || text.includes('surath narzary') || text.includes('metre') ||
    text.includes('rhyme') || text.includes('stanza')
  ) {
    return { unitNumber: 4, unitName: 'Bodo Poetry' };
  }

  // Unit 3: History of Bodo Literature & Periodicals
  if (
    text.includes('bibar') || text.includes('missionary') || text.includes('periodization') ||
    text.includes('history of bodo literature') || text.includes('hathorkhi') || text.includes('alari') ||
    text.includes('periodical') || text.includes('journal') || text.includes('literary history')
  ) {
    return { unitNumber: 3, unitName: 'History of Bodo Literature' };
  }

  // Unit 2: Grammar, Morphology & Syntax
  if (
    text.includes('grammar') || text.includes('morphology') || text.includes('syntax') ||
    text.includes('prefix') || text.includes('suffix') || text.includes('infix') ||
    text.includes('case marker') || text.includes('tense') || text.includes('aspect') ||
    text.includes('noun') || text.includes('verb') || text.includes('sentence') || text.includes('affix')
  ) {
    return { unitNumber: 2, unitName: 'Bodo Grammar, Morphology and Syntax' };
  }

  // Unit 1: Language, Tibeto-Burman & Phonology (Default)
  return { unitNumber: 1, unitName: 'History of Bodo Language and Linguistics' };
}


