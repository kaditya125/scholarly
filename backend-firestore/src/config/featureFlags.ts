/**
 * Phase A integrity feature flags.
 *
 * Read directly from process.env (not the zod `env` schema) so they are purely additive and
 * cannot break env validation. Every flag can be toggled without a code change; the code paths
 * stay in place when disabled. Defaults are chosen to be safe for a live production system:
 *   - verification + repair ON (they only add integrity checks / targeted fixes),
 *   - READY_DEGRADED ON (so a repairable gap does not fail an otherwise-usable source),
 *   - vector metadata backfill ON (the backfill script still requires an explicit run),
 *   - vector re-embed repair OFF by default (it re-embeds and costs money — opt in explicitly).
 */
function boolEnv(name: string, def: boolean): boolean {
  const v = process.env[name];
  if (v === undefined || v === '') return def;
  return /^(1|true|yes|on)$/i.test(v.trim());
}

