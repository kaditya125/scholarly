/**
 * Which cinematic tracks the audio renderer is allowed to mix, as a CSV subset
 * of `music,ambience,sfx,pause`. Empty (the default) means voice only, i.e.
 * today's behavior. This is the incremental-rollout dial for migration
 * Stages 1–3: widen it one track at a time.
 */
export function cinematicTracks(): Set<'music' | 'ambience' | 'sfx' | 'pause'> {
  const raw = (process.env.CINEMATIC_TRACKS || '').trim();
  if (!raw) return new Set();
  const allowed = new Set(['music', 'ambience', 'sfx', 'pause'] as const);
  const out = new Set<'music' | 'ambience' | 'sfx' | 'pause'>();
  for (const part of raw.split(',')) {
    const t = part.trim().toLowerCase();
    if ((allowed as Set<string>).has(t)) out.add(t as 'music' | 'ambience' | 'sfx' | 'pause');
  }
  return out;
}

/** Global cinematic intensity. Defaults to `subtle` so audio never competes with comprehension. */
export function cinematicIntensity(): 'subtle' | 'balanced' | 'dramatic' {
  const v = (process.env.CINEMATIC_INTENSITY || 'subtle').trim().toLowerCase();
  return v === 'balanced' || v === 'dramatic' ? v : 'subtle';
}

/** Mastering loudness target in LUFS. Podcast standard is -16. */
export function targetLufs(): number {
  const n = Number.parseFloat(process.env.TARGET_LUFS || '');
  return Number.isFinite(n) && n <= -6 && n >= -30 ? n : -16;
}

